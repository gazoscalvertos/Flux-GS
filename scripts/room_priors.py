"""Geometry priors for indoor room training: monocular depth maps turned into depth and normal losses.

Plain walls, floors and ceilings have almost no texture, so photometric loss alone leaves them as
cloudy floaters. A monocular depth model still sees them as flat surfaces; these losses pull the
rendered geometry towards that. Used by the room trainer generated by make_room_trainer.py.

Prior maps are relative disparity (larger = closer, unknown scale and shift), as produced by
Depth Anything V2, stored per image as float16 .npy files by depth_priors.py.
"""
import os

import numpy as np
import torch
import torch.nn.functional as F


def load_priors(prior_dir, image_names, device):
    """Load every image's prior disparity map onto the GPU, keyed by image name."""
    priors = {}
    for name in image_names:
        path = os.path.join(prior_dir, os.path.splitext(name)[0] + ".npy")
        if not os.path.exists(path):
            raise FileNotFoundError(f"Missing depth prior for {name}: {path}")
        priors[name] = torch.from_numpy(np.load(path).astype(np.float32)).to(device)
    return priors


def depth_to_normals(depth, K):
    """Camera-space normals from a depth map. depth [H, W], K [3, 3] for that resolution -> [H-2, W-2, 3]."""
    h, w = depth.shape
    v, u = torch.meshgrid(
        torch.arange(h, device=depth.device, dtype=depth.dtype),
        torch.arange(w, device=depth.device, dtype=depth.dtype),
        indexing="ij",
    )
    x = (u - K[0, 2]) / K[0, 0] * depth
    y = (v - K[1, 2]) / K[1, 1] * depth
    points = torch.stack([x, y, depth], dim=-1)
    dx = points[1:-1, 2:] - points[1:-1, :-2]
    dy = points[2:, 1:-1] - points[:-2, 1:-1]
    return F.normalize(torch.cross(dx, dy, dim=-1), dim=-1)


def prior_losses(rendered_depth, alphas, prior_disp, K):
    """Depth and normal losses for one view.

    rendered_depth, alphas: [H, W] at training resolution. prior_disp: [h, w] at prior resolution.
    K: [3, 3] intrinsics at training resolution. Returns (depth_loss, normal_loss), both scalars.
    """
    h, w = prior_disp.shape
    H, W = rendered_depth.shape
    # Compare at the prior's resolution: cheaper, and the prior has no finer detail anyway.
    depth = F.interpolate(rendered_depth[None, None], size=(h, w), mode="area")[0, 0]
    alpha = F.interpolate(alphas[None, None], size=(h, w), mode="area")[0, 0]
    K_small = K.clone()
    K_small[0] *= w / W
    K_small[1] *= h / H

    valid = (alpha > 0.5) & (depth > 1e-4)
    if valid.sum() < 100:
        zero = rendered_depth.sum() * 0.0
        return zero, zero
    disp = 1.0 / depth.clamp(min=1e-4)

    # Depth: Pearson correlation in disparity space, which ignores the prior's unknown scale and shift.
    a = disp[valid] - disp[valid].mean()
    b = prior_disp[valid] - prior_disp[valid].mean()
    depth_loss = 1.0 - (a * b).sum() / (a.norm() * b.norm() + 1e-8)

    # Normals: align the prior to the render's scale (least squares, no gradient), turn it into depth,
    # and match surface orientation. This is what flattens walls the photometric loss leaves cloudy.
    with torch.no_grad():
        A = torch.stack([prior_disp[valid], torch.ones_like(prior_disp[valid])], dim=-1)
        scale, shift = torch.linalg.lstsq(A, disp[valid][:, None]).solution[:, 0]
        prior_depth = 1.0 / (scale * prior_disp + shift).clamp(min=1e-4)
        prior_normals = depth_to_normals(prior_depth, K_small)
    normals = depth_to_normals(depth, K_small)
    inner = valid[1:-1, 1:-1]
    normal_loss = (1.0 - (normals * prior_normals).sum(-1))[inner].mean()
    return depth_loss, normal_loss
